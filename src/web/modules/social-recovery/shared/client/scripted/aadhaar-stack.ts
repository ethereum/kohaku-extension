/**
 * The scripted Aadhaar stack: a double of the Aadhaar proving library, for the
 * build with no deployment and the unit tests. The SDK's own Aadhaar method
 * runs over it unchanged.
 *
 * The prover reports its states on a timer, honours the abort signal, and
 * returns the known-answer vector's proof with the seed it was given and the
 * signal hash of the signal it was given, computed as the library does, so the
 * proof binds the digest the method signs. The proof is stamped with the
 * device clock at prove time and discloses nothing. Its local verifier answers
 * true. `script` makes the prover fail, hang until aborted, prove another
 * nullifier or stamp a QR code older than a day, and the verifier answer false
 * or throw.
 */
import type {
  AadhaarArgsOptions,
  AadhaarPcd,
  AadhaarProgress,
  AadhaarProverArgs
} from '@kohaku-eth/social-recovery/recovery-methods'
import { keccak256, numberToHex } from 'viem'

import type { ScriptedAadhaarOptions, ScriptedAadhaarScript, ScriptedAadhaarStack } from './types'

const DEFAULT_STEP_MS = 400
const DEFAULT_NULLIFIER = 22n
// Older than the one-day window the method enrolls with.
const STALE_AGE_SECONDS = 2 * 24 * 3600
const PROGRESS = ['fetching-wasm', 'fetching-zkey', 'proving', 'completed'] as const

/** The circuit's signal hash: keccak256 of the signal as a 32-byte word, shifted right by three. */
const signalHashOf = (signal: string | undefined): bigint =>
  BigInt(keccak256(numberToHex(BigInt(signal ?? '1'), { size: 32 }))) / 8n

const abortError = (): Error => {
  const error = new Error('The proof was stopped.')
  error.name = 'AbortError'
  return error
}

const nowInSeconds = (): number => Math.floor(Date.now() / 1000)

const pcdOf = (options: AadhaarArgsOptions, nullifier: bigint, timestamp: number): AadhaarPcd => ({
  proof: {
    groth16Proof: {
      pi_a: ['1', '2', '1'],
      pi_b: [
        ['3', '4'],
        ['5', '6'],
        ['1', '0']
      ],
      pi_c: ['7', '8', '1'],
      protocol: 'groth16',
      curve: 'bn128'
    },
    pubkeyHash: '99',
    nullifier: nullifier.toString(),
    timestamp: timestamp.toString(),
    ageAbove18: '0',
    gender: '0',
    pincode: '0',
    state: '0',
    nullifierSeed: options.nullifierSeed.toString(),
    signalHash: signalHashOf(options.signal).toString()
  }
})

export const createScriptedAadhaarStack = (
  options: ScriptedAadhaarOptions = {}
): ScriptedAadhaarStack => {
  const stepMs = options.stepMs ?? DEFAULT_STEP_MS
  let current: ScriptedAadhaarScript = {}
  // The options each circuit argument was generated from, read back by the prover.
  const generated = new WeakMap<AadhaarProverArgs, AadhaarArgsOptions>()

  const prove = (
    args: AadhaarProverArgs,
    onProgress?: AadhaarProgress,
    signal?: AbortSignal
  ): Promise<AadhaarPcd> => {
    const script = current
    const kept = generated.get(args)
    return new Promise((resolve, reject) => {
      if (signal?.aborted) {
        reject(abortError())
        return
      }
      if (!kept) {
        reject(new Error('The circuit arguments were not generated by this prover.'))
        return
      }
      const timers: ReturnType<typeof setTimeout>[] = []
      const onAbort = () => {
        timers.forEach(clearTimeout)
        reject(abortError())
      }
      signal?.addEventListener('abort', onAbort, { once: true })
      const finish = (settle: () => void) => {
        signal?.removeEventListener('abort', onAbort)
        settle()
      }
      const states =
        script.prove === 'hang'
          ? PROGRESS.slice(0, 2)
          : script.prove === 'fail'
          ? PROGRESS.slice(0, 3)
          : PROGRESS
      states.forEach((state, index) =>
        timers.push(setTimeout(() => onProgress?.(state), stepMs * (index + 1)))
      )
      if (script.prove === 'hang') {
        return
      }
      timers.push(
        setTimeout(() => {
          if (script.prove === 'fail') {
            finish(() => reject(new Error('The QR code did not prove.')))
            return
          }
          const timestamp = nowInSeconds() - (script.stale ? STALE_AGE_SECONDS : 0)
          finish(() => resolve(pcdOf(kept, script.nullifier ?? DEFAULT_NULLIFIER, timestamp)))
        }, stepMs * (states.length + 1))
      )
    })
  }

  return {
    generateArgs: async (argsOptions) => {
      const args: AadhaarProverArgs = { nullifierSeed: argsOptions.nullifierSeed.toString() }
      generated.set(args, argsOptions)
      return args
    },
    prove,
    verify: async () => {
      const { verify = true } = current
      if (verify === 'throw') {
        throw new Error('The verifier could not run.')
      }
      return verify
    },
    script: (next) => {
      current = { ...next }
    }
  }
}
